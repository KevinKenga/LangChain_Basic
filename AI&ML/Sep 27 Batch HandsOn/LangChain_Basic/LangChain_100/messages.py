'''
messages : 
System Message : system instructions : you are a helpful assistant
Human Message : user prompt
AI Message : output generated by the model
Tool Message : output generated by a tool (limited to agentic AI)
'''
from langchain_openai import ChatOpenAI
from langchain_core.messages import SystemMessage, HumanMessage, AIMessage
from dotenv import load_dotenv
load_dotenv(override=True)
import os

model = ChatOpenAI(model ="gpt-4o")


# list called as chat history 
# store all the messages

chat_history = [
    SystemMessage(content="You are a helpful assistant. You answer questions based on the context provided.\
        You do not make up answers."),
]

while True:
    user_input = input("User: ")
    if user_input == "exit":
        break

    # Append the user's message to the chat history
    chat_history.append(HumanMessage(content=user_input))

    # Generate a response from the model based on the chat history
    # response is the output given by the model on our prompt
    response = model.invoke(chat_history)

    # Append the model's response to the chat history
    chat_history.append(AIMessage(content=response.content))

    print(f"AI: {response.content}")
    
print("Chat session ended.")
print("Chat history:", chat_history)